    /// <summary>
    /// 合法标签：七元素 + 月兆（月反应体系）+ 星之楔（星反应体系）
    /// </summary>
    private static readonly HashSet<string> ValidTags = ["火元素", "水元素", "风元素", "雷元素", "草元素", "冰元素", "岩元素", "月兆", "星之楔"];

    static AvatarProfiles()
    {
        // Name 必须是标准角色名，写错直接抛异常，防止上线后才发现描述匹配不上
        var knownNames = DefaultAutoFightConfig.CombatAvatarNames;
        var invalidNames = Profiles.Where(p => !knownNames.Contains(p.Name)).Select(p => p.Name).ToList();
        if (invalidNames.Count > 0)
        {
            throw new Exception($"AvatarProfiles 中存在非法角色名（不在 combat_avatar.json 名单内）：{string.Join("、", invalidNames)}");
        }

        // 标签必须合法，且每条有且仅有一个元素标签（BuildTeamSection 依赖它还原"X元素角色"前缀）
        var invalidTags = Profiles.SelectMany(p => p.Tags).Where(t => !ValidTags.Contains(t)).Distinct().ToList();
        if (invalidTags.Count > 0)
        {
            throw new Exception($"AvatarProfiles 中存在非法标签：{string.Join("、", invalidTags)}");
        }

        var badElementCount = Profiles.Where(p => p.Tags.Count(t => t.EndsWith("元素")) != 1).Select(p => p.Name).ToList();
        if (badElementCount.Count > 0)
        {
            throw new Exception($"AvatarProfiles 中以下角色的元素标签缺失或不止一个：{string.Join("、", badElementCount)}");
        }

        // 标签对同样要求由合法标签组成，且同一标签对（顺序无关）不允许重复录入
        var invalidPairTags = TagPairs.SelectMany(p => new[] { p.TagA, p.TagB }).Where(t => !ValidTags.Contains(t)).Distinct().ToList();
        if (invalidPairTags.Count > 0)
        {
            throw new Exception($"TagPairs 中存在非法标签：{string.Join("、", invalidPairTags)}");
        }

        var dupPairs = TagPairs
            .GroupBy(p => string.CompareOrdinal(p.TagA, p.TagB) <= 0 ? (p.TagA, p.TagB) : (p.TagB, p.TagA))
            .Where(g => g.Count() > 1)
            .Select(g => $"{g.Key.Item1} × {g.Key.Item2}")
            .ToList();
        if (dupPairs.Count > 0)
        {
            throw new Exception($"TagPairs 中存在重复标签对：{string.Join("、", dupPairs)}");
        }
    }

    /// <summary>
    /// 取角色档案，缺失返回 null
    /// </summary>
    public static AvatarProfile? TryGet(string name)
    {
        return Profiles.FirstOrDefault(p => p.Name == name);
    }

    /// <summary>
    /// 把队伍展开成提示词的"当前队伍"段落
    /// 有档案的角色展开为"名字：X元素角色、月兆角色等（顿号连接），描述"；缺失档案的角色只列名字并记日志
    /// </summary>
    public static string BuildTeamSection(List<string> avatarNames, ILogger logger)
    {
        var lines = new List<string>();
        foreach (var name in avatarNames)
        {
            var profile = TryGet(name);
            if (profile != null)
            {
                // 元素标签还原为"X元素角色"，其余标签（月兆/星之楔）加"角色"后缀，统一用顿号连接
                var element = profile.Tags.FirstOrDefault(t => t.EndsWith("元素"));
                var others = profile.Tags.Where(t => !t.EndsWith("元素")).Select(t => $"{t}角色").ToList();
                if (element != null)
                {
                    others.Insert(0, $"{element}角色");
                }
                var head = string.Join("、", others);
                lines.Add($"- {name}：{head}，{GetAdaptedDescription(profile)}");
            }
            else
            {
                logger.LogWarning("角色 {Name} 无内置战术描述，提示词中将只列出名字", name);
                lines.Add($"- {name}");
            }
        }

        return string.Join("\n", lines);
    }

    /// <summary>
    /// 取角色适配后的描述：基础攻击句中含蓄力重击的（均为弓箭手），将该句替换为重击不适配的说明
    /// </summary>
    private static string GetAdaptedDescription(AvatarProfile profile)
    {
        var separatorIndex = profile.Description.IndexOf('；');
        if (separatorIndex < 0)
        {
            return profile.Description;
        }
        var firstSentence = profile.Description[..separatorIndex];
        if (firstSentence.Contains("基础攻击") && firstSentence.Contains("重击") && firstSentence.Contains("蓄力"))
        {
            return "基础攻击普攻与下落为物理伤害，弓箭手角色重击暂无法适配，禁止使用" + profile.Description[separatorIndex..];
        }
        return profile.Description;
    }

    /// <summary>
    /// 取两个标签的交叉描述，顺序无关，未录入返回 null
    /// </summary>
    public static string? TryGetTagPair(string tagA, string tagB)
    {
        return TagPairs.FirstOrDefault(p => p.TagA == tagA && p.TagB == tagB || p.TagA == tagB && p.TagB == tagA)?.Description;
    }

    /// <summary>
    /// 把队伍内标签的两两交叉描述展开成提示词段落
    /// 稀疏：只展开已录入的标签对，未录入的组合不输出
    /// </summary>
    public static string BuildTagPairSection(List<string> avatarNames)
    {
        var tags = avatarNames
            .Select(name => TryGet(name)?.Tags)
            .Where(t => t != null)
            .SelectMany(t => t!)
            .Distinct()
            .ToList();

        var lines = new List<string>();
        for (var i = 0; i < tags.Count; i++)
        {
            for (var j = i + 1; j < tags.Count; j++)
            {
                var desc = TryGetTagPair(tags[i], tags[j]);
                if (desc != null)
                {
                    lines.Add($"- {tags[i].Replace("元素", "")} × {tags[j].Replace("元素", "")}：{desc}");
                }
            }
        }

        return string.Join("\n", lines);
    }
